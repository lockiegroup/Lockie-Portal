<script>
const csrfToken = document.querySelector('meta[name="csrf-token"]').content;
document.getElementById('code').addEventListener('keydown', e => { if (e.key === 'Enter') activate(); });

async function activate() {
    const code = document.getElementById('code').value.trim();
    const btn  = document.getElementById('btn');
    const msg  = document.getElementById('msg');
    if (code.length !== 6) { msg.className = 'err'; msg.textContent = 'Enter a 6-digit code.'; return; }
    btn.disabled = true;
    msg.className = ''; msg.textContent = 'Activating…';
    try {
        const res  = await fetch('{{ route('clocking.kiosk.activate') }}', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json', 'X-CSRF-TOKEN': csrfToken },
            body: JSON.stringify({ code }),
        });
        const json = await res.json();
        if (res.ok) {
            msg.className = 'ok';
            msg.textContent = 'Registered as "' + json.device + '". Loading kiosk…';
            setTimeout(() => location.reload(), 800);
        } else {
            msg.className = 'err';
            msg.textContent = json.error || 'Activation failed.';
            btn.disabled = false;
        }
    } catch(e) {
        msg.className = 'err'; msg.textContent = 'Network error.'; btn.disabled = false;
    }
}
</script>
